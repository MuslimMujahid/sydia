/**
 * Bundles the note editor (editor/editor.ts: Tiptap with the web's schema)
 * into one self-contained HTML page and writes it as a TypeScript module the
 * app loads into a WebView. Run with `bun run build:editor` after changing
 * anything under editor/.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { EDITOR_CSS } from "../editor/styles";

const root = path.resolve(import.meta.dir, "..");
const outputPath = path.join(root, "src/lib/editor/editor-html.generated.ts");

const result = await globalThis.Bun.build({
  entrypoints: [path.join(root, "editor/editor.ts")],
  target: "browser",
  format: "iife",
  minify: true,
  sourcemap: "none",
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

const [bundle] = result.outputs;
if (!bundle) {
  console.error("The editor build produced no output.");
  process.exit(1);
}

// Keep an inline script from closing its own tag.
const script = (await bundle.text()).replace(/<\/script/gi, "<\\/script");

const html = [
  "<!doctype html>",
  '<html lang="id"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, viewport-fit=cover">',
  `<style>${EDITOR_CSS}</style></head><body>`,
  '<div id="app">',
  '<textarea id="title" rows="1" aria-label="Judul catatan" hidden></textarea>',
  '<div id="heading" hidden><h1 id="heading-title"></h1><p id="heading-subtitle"></p></div>',
  '<div id="editor"></div>',
  "</div>",
  `<script>${script}</script>`,
  "</body></html>",
].join("");

writeFileSync(
  outputPath,
  [
    "// Generated by scripts/build-editor.mjs from editor/*.ts. Do not edit by",
    "// hand; run `bun run build:editor` after changing the editor source.",
    `export const EDITOR_HTML: string = ${JSON.stringify(html)};`,
    "",
  ].join("\n")
);

console.log(
  `Wrote ${path.relative(root, outputPath)} (${Math.round(html.length / 1024)} KB)`
);
