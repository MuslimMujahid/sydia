const assert = require('node:assert/strict');
const childProcess = require('node:child_process');
const {
  readFile,
  readdir,
  writeFile,
  mkdtemp,
  rm,
} = require('node:fs/promises');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { ConfigService } = require('@nestjs/config');
const { zipSync, unzipSync } = require('fflate');
const {
  DocumentParserService,
  DocumentParserSettings,
  DOCUMENT_POLICY_VERSION,
} = require('../../dist/src/infra/document-parser');
const {
  documentParserFailureMessage,
} = require('../../dist/src/modules/documents/document-parser-errors');
const { createFixtures } = require('./fixtures.cjs');
const { createVisualFixtures } = require('./visual-fixtures.cjs');

async function main() {
  const directory = await mkdtemp(join(tmpdir(), 'sydia-failure-fixtures-'));
  const originalFork = childProcess.fork;
  const children = [];
  childProcess.fork = (...args) => {
    const child = originalFork(...args);
    children.push({
      child,
      closed: new Promise((resolve) => child.once('close', resolve)),
    });
    return child;
  };
  const existingTemporaryFiles = new Set(await readdir(tmpdir()));
  const results = [];
  try {
    const documents = await createFixtures(directory);
    const visuals = await createVisualFixtures();
    const archive = unzipSync(documents['invoice.docx']);
    archive['word/large-padding.bin'] = new Uint8Array(2 * 1024 * 1024);
    const expandedArchive = Buffer.from(zipSync(archive));
    const encryptedPdf = Buffer.from(
      (await readFile(join(__dirname, 'encrypted-pdf.base64'), 'utf8')).trim(),
      'base64',
    );
    for (const [name, buffer, config, expected] of [
      ['encrypted.pdf', encryptedPdf, {}, 'PASSWORD_REQUIRED'],
      [
        'expanded.docx',
        expandedArchive,
        { BACKEND_DOCUMENT_MAX_ARCHIVE_BYTES: 1024 * 1024 },
        'ARCHIVE_LIMIT_EXCEEDED',
      ],
      [
        'pixels.docx',
        visuals['embedded-flowchart.docx'],
        { BACKEND_DOCUMENT_MAX_IMAGE_PIXELS: 10000 },
        'IMAGE_LIMIT_EXCEEDED',
      ],
      [
        'image-bytes.docx',
        visuals['embedded-flowchart.docx'],
        { BACKEND_DOCUMENT_MAX_IMAGE_BYTES: 1024 },
        'IMAGE_LIMIT_EXCEEDED',
      ],
      ['mislabeled.xlsx', documents['invoice.docx'], {}, 'FORMAT_MISMATCH'],
      [
        'timeout.pdf',
        documents['mixed.pdf'],
        { BACKEND_DOCUMENT_TIMEOUT_MS: 1000 },
        'EXTRACTION_TIMEOUT',
      ],
    ]) {
      const service = new DocumentParserService(
        new DocumentParserSettings(
          new ConfigService({
            ...config,
          }),
        ),
      );
      const started = Date.now();
      try {
        await assert.rejects(
          service.parse({
            originalname: name,
            mimetype: 'application/octet-stream',
            buffer,
          }),
          { code: expected, retryable: false },
        );
        const message = documentParserFailureMessage(expected);
        assert(message.length > 20);
        if (name === 'encrypted.pdf') assert(/kata sandi/.test(message));
        if (name === 'timeout.pdf')
          assert(
            Date.now() - started < 10000,
            'hard parser timeout did not settle promptly',
          );
        results.push({
          name,
          rejected: expected,
          durationMs: Date.now() - started,
          inputBytes: buffer.length,
          settings: config,
        });
      } finally {
        await service.onModuleDestroy();
      }
    }
    let timer;
    try {
      await Promise.race([
        Promise.all(children.map((value) => value.closed)),
        new Promise((_, reject) => {
          timer = setTimeout(
            () => reject(new Error('Parser children remain after shutdown')),
            5000,
          );
        }),
      ]);
    } finally {
      clearTimeout(timer);
    }
    assert(
      children.every(
        (value) =>
          value.child.exitCode !== null || value.child.signalCode !== null,
      ),
    );
    assert.deepEqual(
      (await readdir(tmpdir())).filter(
        (name) =>
          name.startsWith('sydia-ocr-') && !existingTemporaryFiles.has(name),
      ),
      [],
    );
    const report = {
      generatedAt: new Date().toISOString(),
      policyVersion: DOCUMENT_POLICY_VERSION,
      passed: true,
      paidProviderCalls: 0,
      parserChildrenClosed: children.length,
      ocrTemporaryFilesRemoved: true,
      encryptedFixture:
        'Synthetic blank PDF generated by pypdf 6.10.0, password fixture-password',
      results,
    };
    if (process.argv[2])
      await writeFile(process.argv[2], JSON.stringify(report, null, 2) + '\n');
    process.stdout.write(JSON.stringify(report) + '\n');
  } finally {
    childProcess.fork = originalFork;
    await rm(directory, { recursive: true, force: true });
  }
}

main().catch((error) => {
  process.stderr.write(`Parser failure check failed: ${error.message}\n`);
  process.exitCode = 1;
});
